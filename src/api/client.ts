/**
 * Fetch all claims
 */
export const fetchClaims = async (): Promise<Claim[]> => {
  const response = await axiosInstance.get<Claim[]>('/claims');
  return response.data;
};

/**
 * Fetch claims specifically for an item ID
 */
export const fetchClaimsByItemId = async (itemId: string): Promise<Claim[]> => {
  const response = await axiosInstance.get<Claim[]>('/claims', {
    params: { itemId },
  });
  return response.data;
};

/**
 * Create a new claim (POST)
 * Accepts ClaimCreateInput (which omits 'id' auto-generated by the backend)
 */
export const createClaim = async (claimData: ClaimCreateInput): Promise<Claim> => {
  const response = await axiosInstance.post<Claim>('/claims', claimData);
  return response.data;
};

/**
 * Update claim status
 */
export const updateClaimStatus = async (
  id: string,
  status: 'pending' | 'approved' | 'rejected'
): Promise<Claim> => {
  const response = await axiosInstance.patch<Claim>(`/claims/${id}`, { status });
  return response.data;
};

export default axiosInstance;
